/** 离开意图识别（第十九条：识别到退出意图须及时停止，不得阻碍） */
const EXIT_PATTERNS = /(不想聊了|不聊了|先不聊|我要走了|我先下了|下线了|不玩了|再见|拜拜|结束对话|我要删了|退出吧|不说了)/

