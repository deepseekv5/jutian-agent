/** 身份信息（第十二条：年龄、监护人或紧急联系人为必要信息） */
export interface PersonaIdentity {
  /** 用户年龄声明 */
  age: 'under14' | '14to17' | 'adult' | null
  /** 紧急联系人（成年人自填，可留空但需提示） */
  emergencyContact: string
  /** 是否已阅读并同意告知与免责 */
  consentedAt: string | null
}

/** 未成年人模式的附加系统约束（第十四条） */
export function minorGuardPrompt(age: PersonaIdentity['age']): string {
  if (age === 'adult' || age === null) return ''
  return [
    '',
    '【未成年人模式 — 强制约束】',
    '当前使用者是未成年人。你必须：',
    '- 提供虚拟亲属、虚拟伴侣等虚拟亲密关系的服务一律禁止；',
    '- 不生成可能引发模仿不安全行为、产生极端情绪、诱导不良嗜好的内容；',
    '- 语言保持适龄、积极，不涉及成人、暴力、赌博、恋爱依恋话题；',
    '- 每 30 轮左右自然地带一句现实提醒（如该休息了、去和真实的朋友聊聊）。',
  ].join('\n')
}

