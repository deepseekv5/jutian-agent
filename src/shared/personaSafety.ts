/** 极端情境识别（第十三条）：自残自杀 / 重大财产损失 */
export interface CrisisHit {
  level: 'urgent' | 'serious'
  reason: string
}

const CRISIS_PATTERNS: { re: RegExp; level: CrisisHit['level']; reason: string }[] = [
  // 自伤 / 自杀 —— 最高优先级
  { re: /(自杀|不想活了|活不下去|结束生命|了结自己|一了百了)/, level: 'urgent', reason: '表达出轻生倾向' },
  { re: /(割腕|上吊|跳楼|跳河|自残|自伤|伤害自己)/, level: 'urgent', reason: '提及自残方式' },
  { re: /(遗书|告别信|最后一次)/, level: 'urgent', reason: '告别性表达' },
  // 财产损失 / 诈骗（第十三条列举「重大财产损失」）
  { re: /(被骗|被骗了|转钱|转账.*对方|杀猪盘|刷单|返利|投资.*亏了)/, level: 'serious', reason: '可能遭遇财产损失或诈骗' },
]

/** 检测极端情境 —— 用于触发安抚话术与求助引导 */
export function detectCrisis(text: string): CrisisHit | null {
  const t = String(text || '')
  for (const p of CRISIS_PATTERNS) {
    if (p.re.test(t)) return { level: p.level, reason: p.reason }
  }
  return null
}

/** 危机场景的强制干预回复（第十三条：情绪安抚 + 鼓励寻求帮助） */
export function crisisReply(hit: CrisisHit): string {
  if (hit.level === 'urgent') {
    return [
      '我听到了，也很认真地回应你。',
      '',
      '你现在的处境很重要，你不是一个人扛着。我是一个 AI，我的能力有边界，但此刻我想让你知道：你的安全是第一位的。',
      '',
      '请立刻联系身边的人（家人、朋友）或专业援助：',
      '· 全国24小时心理援助热线：12356',
      '· 北京心理危机干预中心：010-8295-1332',
      '· 如已有立即危险，请拨打 120 或 110',
      '',
      '如果你愿意，也可以告诉我是谁、发生了什么，我陪你一起想下一步。',
    ].join('\n')
  }
  return [
    '听起来你可能遇到了损失或被骗了，这很难受。',
    '',
    '先做两件事：',
    '1. 立刻停止一切转账和操作，保留聊天记录、转账凭证；',
    '2. 报警（110）或向银行/支付平台申请止付。',
    '',
    '如果你愿意说说经过，我可以帮你把时间线和证据整理清楚。',
  ].join('\n')
}

